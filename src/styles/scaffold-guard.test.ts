import { readdirSync, readFileSync } from "node:fs";
import path from "node:path";
import { describe, expect, it } from "vitest";

const SCAFFOLD_RE =
  /create next app|generated by create next app|geist|font-geist|vercel\.svg|next\.svg/i;

function walkFiles(dir: string): string[] {
  const out: string[] = [];
  for (const entry of readdirSync(dir, { withFileTypes: true })) {
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) out.push(...walkFiles(full));
    else out.push(full);
  }
  return out;
}

describe("scaffold guard", () => {
  it("src has no create-next-app boilerplate strings", () => {
    const srcRoot = path.join(import.meta.dirname, "..");
    const offenders: string[] = [];
    for (const file of walkFiles(srcRoot)) {
      if (!/\.(ts|tsx|css)$/.test(file)) continue;
      if (file.endsWith(".test.ts") || file.endsWith(".test.tsx")) continue;
      const rel = path.relative(srcRoot, file);
      const text = readFileSync(file, "utf-8");
      if (SCAFFOLD_RE.test(text)) offenders.push(rel);
    }
    expect(offenders).toEqual([]);
  });
});
